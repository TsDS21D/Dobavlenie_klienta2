# web_calculators/apps.py
"""
Конфигурация приложения "Веб-калькуляторы".

Приложение отвечает за создание и обслуживание публичных калькуляторов
для внешних сайтов (например, bukva-a.ru). Предоставляет:
- модели описания калькуляторов (WebCalculator, WebCalculatorComponent, ...),
- публичный API для расчёта цен без записи в БД,
- страницу-витрину калькулятора на своём домене (для тестирования).

Приложение работает независимо от секции "Справочник шаблонов" — у него
свои модели и своя логика. Обе секции дополняют друг друга.
"""

from django.apps import AppConfig


class WebCalculatorsConfig(AppConfig):
    """
    Класс конфигурации приложения "web_calculators".
    Задаёт тип автоинкрементного поля, имя приложения и его отображаемое имя.
    """

    # Тип поля первичного ключа для всех моделей приложения.
    # BigAutoField — 64-битное автоинкрементное число (выдерживает большие объёмы).
    default_auto_field = 'django.db.models.BigAutoField'

    # Системное имя приложения — должно совпадать с именем папки.
    name = 'web_calculators'

    # Человекочитаемое имя — отображается в административной панели Django.
    verbose_name = 'Веб-калькуляторы для сайтов'